create or replace function public.mcr_omzet_vorig_jaar(p_van date, p_tot date)
returns table(datum date, datum_vorig date, kraam_id uuid, kraam_naam text,
              pin numeric, contant numeric, totaal numeric, opmerking text)
language sql stable security definer set search_path to 'public'
as $$
  select h.datum + 364, h.datum, h.kraam_id, h.kraam_naam, h.pin, h.contant, h.totaal, d.opmerking
    from public.mcr_omzet_historie h
    left join public.mcr_omzet_historie_dag d on d.datum = h.datum
   where h.datum between p_van - 364 and p_tot - 364
     and public.mag_mcr_omzet()
   order by h.datum, h.kraam_naam
$$;
revoke all on function public.mcr_omzet_vorig_jaar(date,date) from public, anon;
