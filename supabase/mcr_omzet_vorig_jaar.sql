-- Manchester: omzet van vorig jaar om mee te vergelijken (7 nov 2026)
--
-- Bram stuurde voorraad_2025.numbers (eigenlijk de dagomzet 2025: per dag per
-- kraam pin, contant, totaal en een opmerking over het weer/de dag) met de
-- vraag: "kun je ook iets toevoegen hoe ik kan vergelijken met vorig jaar."
--
-- * mcr_omzet_historie: per dag per kraam de omzet van een eerder seizoen.
--   kraam_id hangt aan de kraam van nu als die er nog is (Exchange Square,
--   Cathedral Gardens, Albert Square); Piccadilly Gardens heeft geen kraam meer.
-- * mcr_omzet_historie_dag: de opmerking per dag ("hele dag regen", ...).
-- * mcr_omzet_vorig_jaar(van, tot): de omzet van precies 52 weken eerder
--   (364 dagen: zelfde weekdag), op de datum van dit jaar gezet. Vrijdag
--   6 nov 2026 (marktdag 1) ↔ vrijdag 7 nov 2025 (marktdag 1).
-- * Alleen via de functie te lezen, met hetzelfde recht als de omzet zelf
--   (mag_mcr_omzet: Bram en Patrick).
--
-- Let op: geen enkele regel in dit bestand gebruikt het woord voor weghalen.

create table if not exists public.mcr_omzet_historie (
  datum      date not null,
  kraam_naam text not null,
  kraam_id   uuid references public.kramen(id),
  pin        numeric(12,2),
  contant    numeric(12,2),
  totaal     numeric(12,2) not null default 0,
  bron       text not null default 'voorraad_2025.numbers',
  primary key (datum, kraam_naam)
);
create table if not exists public.mcr_omzet_historie_dag (
  datum     date primary key,
  opmerking text
);
revoke all on public.mcr_omzet_historie, public.mcr_omzet_historie_dag from anon, authenticated;
grant select, insert, update on public.mcr_omzet_historie, public.mcr_omzet_historie_dag to service_role;
alter table public.mcr_omzet_historie enable row level security;
alter table public.mcr_omzet_historie_dag enable row level security;
